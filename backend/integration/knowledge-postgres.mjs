import test from 'node:test';
import assert from 'node:assert/strict';
import {knowledgeAction,closeKnowledgePool} from '../knowledge-base.js';

test('full PostgreSQL knowledge lifecycle isolates collections and learns from feedback',async(t)=>{
 t.after(closeKnowledgePool);
 const suffix=Date.now().toString(36);
 const title='CI business services '+suffix;
 const content='We provide website accessibility, lead capture, conversion testing and responsive design. '+suffix;
 const created=await knowledgeAction('ingest',{collection:'business',title,content});
 assert.match(created.id,/^[0-9a-f-]{36}$/);
 assert.equal(created.duplicate,false);
 const again=await knowledgeAction('ingest',{collection:'business',title,content});
 assert.equal(again.duplicate,true);
 const search=await knowledgeAction('search',{collection:'business',query:'accessibility'});
 assert.ok(search.results.some(x=>x.id===created.id));
 const separate=await knowledgeAction('search',{collection:'prospects',query:suffix});
 assert.ok(!separate.results.some(x=>x.id===created.id));
 const context=await knowledgeAction('context',{collection:'business',query:'accessibility'});
 assert.ok(context.context.some(x=>x.id===created.id));
 assert.ok(context.context.every(x=>x.collection==='business'));
 const offer=await knowledgeAction('offer-preview',{query:'accessibility',prospect:'Example Company'});
 assert.equal(offer.readyForSending,false);
 assert.equal(offer.requiresHumanReview,true);
 assert.ok(offer.evidence.some(x=>x.documentId===created.id));
 await knowledgeAction('feedback',{documentId:created.id,signal:'incorrect'});
 await knowledgeAction('feedback',{documentId:created.id,signal:'incorrect'});
 const disputed=await knowledgeAction('search',{collection:'business',query:'accessibility'});
 assert.equal(disputed.results.find(x=>x.id===created.id).needs_review,true);
 const filtered=await knowledgeAction('context',{collection:'business',query:'accessibility'});
 assert.ok(!filtered.context.some(x=>x.id===created.id));
 const outcome=await knowledgeAction('record-outcome',{documentId:created.id,stage:'qualified'});
 assert.equal(outcome.recorded,true);
 const summary=await knowledgeAction('outcome-summary');
 assert.ok(summary.outcomes.some(x=>x.collection==='business'&&x.stage==='qualified'));
 const listed=await knowledgeAction('list',{collection:'business'});
 assert.ok(listed.documents.some(x=>x.id===created.id));
 const archived=await knowledgeAction('archive',{documentId:created.id});
 assert.equal(archived.archived,true);
 const after=await knowledgeAction('search',{collection:'business',query:'accessibility'});
 assert.ok(!after.results.some(x=>x.id===created.id));
});
